/**
 * Every file the `@hatch/ui` generator owns, with its expected content.
 * `generate.ts` writes them; the sync test compares them with the files on
 * disk, so a token, icon or component change that was not regenerated fails.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ACCENT_NAMES, buildAppTheme } from '../theme/build.ts';
import { buildTailwindExtension } from '../theme/tailwind.ts';
import { renderTokenModule } from './tokens.ts';
import { buildCatalogueReference } from './catalogue.ts';
import { buildIcons, renderIconModule } from './icons.ts';

export const UI_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
export const REPO_ROOT = path.resolve(UI_ROOT, '../..');

export type GeneratedFile = { path: string; content: string };

/** Formats `content` as Oxfmt formats the file at `filePath`. */
export function formatAs(filePath: string, content: string): string {
  const oxfmt = path.join(REPO_ROOT, 'node_modules/.bin/oxfmt');
  return execFileSync(oxfmt, [`--stdin-filepath=${filePath}`], {
    cwd: REPO_ROOT,
    input: content,
    encoding: 'utf8',
  });
}

function json(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`;
}

/**
 * The notification card compiler and its catalog, copied from
 * `packages/hatch-platform-api` (the platform's own source, so an App
 * compiles a card exactly as the platform does). `@hatch/ui` ships only its
 * own `src/`, so the files are copied rather than imported; their imports of
 * each other are renamed with them. All are dependency-free.
 */
export const CARD_CONTENT_FILES: Readonly<Record<string, string>> = {
  'notification-content': 'catalog.gen',
  'notification-card-markup': 'markup.gen',
  'notification-content-compile': 'compile.gen',
  'notification-content-text': 'text.gen',
  'notification-reply': 'reply.gen',
  'notification-reply-form': 'reply-form.gen',
  'notification-url': 'url.gen',
  'deep-link': 'deep-link.gen',
};

const PLATFORM_API = path.join(REPO_ROOT, 'packages/hatch-platform-api');

function copiedModule(source: string): string {
  const text = fs.readFileSync(path.join(PLATFORM_API, `${source}.ts`), 'utf8');
  const renamed = text.replace(
    /from '\.\/([a-z-]+)'/g,
    (_match, name: string) => {
      const target = CARD_CONTENT_FILES[name];
      if (!target) {
        throw new Error(`${source}.ts imports ./${name}, which is not copied`);
      }
      return `from './${target}'`;
    },
  );
  return `// Generated by sdk-internal/ui/scripts/generate.ts from\n// packages/hatch-platform-api/${source}.ts; edit that file instead.\n${renamed}`;
}

export function generatedFiles(): GeneratedFile[] {
  const icons = buildIcons();
  const files: GeneratedFile[] = [
    { path: 'src/theme.json', content: json(buildAppTheme()) },
    { path: 'src/tailwind.json', content: json(buildTailwindExtension()) },
    { path: 'src/icons/icons.gen.ts', content: renderIconModule(icons) },
    { path: 'src/core/tokens.gen.ts', content: renderTokenModule() },
    {
      path: 'gallery/web/themes.json',
      content: json(
        Object.fromEntries(
          ACCENT_NAMES.map((accent) => [accent, buildAppTheme({ accent })]),
        ),
      ),
    },
    {
      path: '../../skills/building-apps/references/design-system.md',
      content: buildCatalogueReference(icons),
    },
    ...Object.entries(CARD_CONTENT_FILES).map(([source, target]) => ({
      path: `src/card/content/${target}.ts`,
      content: copiedModule(source),
    })),
    {
      path: 'gallery/app/card-examples.gen.ts',
      content: copiedModule('notification-content-examples'),
    },
  ];
  return files.map((file) => {
    const absolute = path.resolve(UI_ROOT, file.path);
    return { path: absolute, content: formatAs(absolute, file.content) };
  });
}
