/** Client-neutral SDK payload, always taken from this running platform build. */
import esbuildPackage from 'esbuild/package.json' with { type: 'json' };
import typescriptPackage from 'typescript/package.json' with { type: 'json' };
import platformPackage from '../../../package.json' with { type: 'json' };
import {
  APP_TASK_OPTIONS_PROTO,
  APP_TASK_OPTIONS_PROTO_FILE,
  PLATFORM_APP_BUF_GEN_YAML,
} from '~agent/app-codegen';
import {
  SDK_DENO_TYPES,
  SDK_DENO_TYPES_LICENSE,
  SDK_DEFINITIONS,
  appMaterializedSdkDefinitions,
  sdkImports,
  sdkToolchainFiles,
} from '../../../sdk-internal/definitions';

// Vite embeds only the SDK artifacts generated by this build. Runtime cwd and
// the source repository are not part of the public SDK delivery contract.
const builtFiles = import.meta.glob<string>(
  [
    '../../../sdk-internal/{app,data,ui}/package.json',
    '../../../sdk-internal/{app,data,ui}/dist/**/*',
  ],
  { eager: true, query: '?raw', import: 'default' },
);

// The same locked declarations the Runner copies from node_modules.
const denoTypes = import.meta.glob<string>(
  [
    '../../../node_modules/@types/deno/index.d.ts',
    '../../../node_modules/@types/deno/LICENSE',
  ],
  { eager: true, query: '?raw', import: 'default' },
);

function denoTypesFile(name: string): string {
  const contents = denoTypes[`../../../node_modules/@types/deno/${name}`];
  if (contents === undefined)
    throw new Error('Platform type declarations are missing.');
  return contents;
}

/** Versions of the tools the platform itself runs, for local preparation. */
export function platformTooling() {
  return {
    bufVersion: platformPackage.devDependencies['@bufbuild/buf'].replace(
      /^\^/,
      '',
    ),
    protocGenEsVersion: platformPackage.devDependencies[
      '@bufbuild/protoc-gen-es'
    ].replace(/^\^/, ''),
    typescriptVersion: typescriptPackage.version,
    esbuildVersion: esbuildPackage.version,
    pnpmVersion: platformPackage.packageManager.replace(/^pnpm@/, ''),
  };
}

export async function sdkPayload() {
  const definitions = SDK_DEFINITIONS;
  const files: { path: string; contentBase64: string }[] = [];
  // Native-only libraries ship beside the App SDK, as materialization does.
  const packages = appMaterializedSdkDefinitions();
  for (const definition of packages) {
    const prefix = `../../../sdk-internal/${definition.directory}/`;
    const entries = Object.entries(builtFiles).filter(([file]) =>
      file.startsWith(prefix),
    );
    // Every export's runtime and type targets must ship, or the import map
    // would point a source at files it does not have.
    const shipped = new Set(entries.map(([file]) => file.slice(prefix.length)));
    for (const entry of Object.values(definition.manifest.exports)) {
      for (const target of [entry.default, entry.types]) {
        if (!shipped.has(target.replace(/^\.\//, ''))) {
          throw new Error(
            `Built SDK artifacts are missing: ${definition.manifest.name} ${target}.`,
          );
        }
      }
    }
    for (const [file, contents] of entries)
      files.push({
        path: `sdk/${definition.manifest.name}/${file.slice(prefix.length)}`,
        contentBase64: Buffer.from(contents).toString('base64'),
      });
  }
  files.push({
    path: 'import-map.json',
    contentBase64: Buffer.from(
      JSON.stringify({ imports: sdkImports(definitions) }, null, 2),
    ).toString('base64'),
  });
  files.push(
    {
      path: 'buf.gen.yaml',
      contentBase64: Buffer.from(PLATFORM_APP_BUF_GEN_YAML).toString('base64'),
    },
    {
      path: APP_TASK_OPTIONS_PROTO_FILE,
      contentBase64: Buffer.from(APP_TASK_OPTIONS_PROTO).toString('base64'),
    },
  );
  // Generated configuration is delivered, not rebuilt by the client, so the
  // platform, the Runner and the CLI check a source against the same bytes.
  for (const [file, contents] of Object.entries({
    ...sdkToolchainFiles(),
    [SDK_DENO_TYPES]: denoTypesFile('index.d.ts'),
    [SDK_DENO_TYPES_LICENSE]: denoTypesFile('LICENSE'),
  }))
    files.push({
      path: file,
      contentBase64: Buffer.from(contents).toString('base64'),
    });
  return { files, tooling: platformTooling() };
}
